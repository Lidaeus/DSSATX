#!/usr/bin/env python3
"""Assemble v2 trial-calibration bundles for 25SP/25FA/26SP.

Per docs/三季FileA_FileT与不确定性适配计划_v1_20260726.md Section 6:
  1. Copy TMX/SOIL.SOL/WTH/DSSBatch.v48 from existing v1 bundles (FileX retention).
  2. Write generated TMA/TMT/observation_uncertainty.csv/fruit_quality_match_audit.csv/
     soil_water_observations.csv/treatment_exclusion_audit.csv from DSSAT输出_v2/.
  3. Generate input_manifest.json with SHA-256 for all files, source workbook SHAs,
     generator SHAs, processing map, and FileX retention proof.

Bundle layout (per season):
  data/user/experiments/xxql{2501,2502,2601}_actual_trial_calibration_v2_20260726/
    XXQL{2501,2502,2601}.TMX                  (copied from v1 bundle)
    XXQL{2501,2502,2601}.TMA                  (generated by build_trial_observations_v2)
    XXQL{2501,2502,2601}.TMT                  (generated by build_trial_observations_v2)
    SOIL.SOL                                  (copied from v1 bundle)
    {XXLI2502,XXN92501,XXQL2601}.WTH          (copied from v1 bundle)
    DSSBatch.v48                              (copied from v1 bundle)
    observation_uncertainty.csv               (generated)
    fruit_quality_match_audit.csv             (generated)
    soil_water_observations.csv               (generated)
    soil_water_layer_mapping.csv              (generated)
    soil_water_match_audit.csv                (generated)
    treatment_exclusion_audit.csv             (25SP only; generated)
    trial_generator_log.json                  (copied from DSSAT输出_v2)
    soil_water_generator_log.json             (copied from DSSAT输出_v2)
    input_manifest.json                       (generated by this script)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path

EXPERIMENTS_DIR = Path(r"D:\Tomato_Cal\data\user\experiments")
REF_DIR = Path(r"D:\Tomato_Cal\data\user\ref\DSSAT文件")

# Source FileX bundles for TMX/SOIL.SOL/WTH/DSSBatch.v48.
# Updated 2026-07-26: user refreshed FileX (added virtual +1-day harvest events
# to capture final-harvest data via DSSAT's N+1 reporting behavior). The new
# authoritative source is data/user/experiments/XXQL{2501,2502,2601}/ (no
# suffix), replacing the prior v1 bundles.
SOURCE_BUNDLES = {
    "25SP": EXPERIMENTS_DIR / "XXQL2501",
    "25FA": EXPERIMENTS_DIR / "XXQL2502",
    "26SP": EXPERIMENTS_DIR / "XXQL2601",
}

# Weather file names per season. 25SP shares the same weather station as
# 25FA (XXLI2502.WTH); 26SP has its own (XXQL2601.WTH). Verified by listing
# data/user/experiments/XXQL{2501,2502,2601}/.
WEATHER_FILES = {
    "25SP": "XXLI2502.WTH",
    "25FA": "XXLI2502.WTH",
    "26SP": "XXQL2601.WTH",
}

# Excode and season folder
SEASON_INFO = {
    "25SP": {"excode": "XXQL2501", "folder": "2025春", "bundle_name": "xxql2501_actual_trial_calibration_v2_20260726"},
    "25FA": {"excode": "XXQL2502", "folder": "2025秋", "bundle_name": "xxql2502_actual_trial_calibration_v2_20260726"},
    "26SP": {"excode": "XXQL2601", "folder": "2026春", "bundle_name": "xxql2601_actual_trial_calibration_v2_20260726"},
}

# Treatment exclusion per season (25SP only)
TREATMENT_EXCLUSION = {
    "25SP": {"excluded_tn": [1, 6, 7, 8], "included_tn": [2, 3, 4, 5, 9, 10, 11, 12, 13, 14],
             "reason": "缺少实际 FileX 管理/初始条件定义"},
    "25FA": {"excluded_tn": [], "included_tn": list(range(1, 13)), "reason": ""},
    "26SP": {"excluded_tn": [], "included_tn": list(range(1, 13)), "reason": ""},
}


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def file_record(path: Path) -> dict:
    return {
        "name": path.name,
        "sha256": sha256_file(path),
        "bytes": path.stat().st_size,
    }


def copy_file(src: Path, dst: Path) -> None:
    """Copy a file, preserving content. Overwrites if dst exists."""
    shutil.copy2(src, dst)


def assemble_bundle(season: str, generators_sha: dict[str, str]) -> Path:
    info = SEASON_INFO[season]
    excode = info["excode"]
    bundle_dir = EXPERIMENTS_DIR / info["bundle_name"]
    bundle_dir.mkdir(parents=True, exist_ok=True)
    # Older v2 assembly runs left the source-named generator_log.json beside
    # the manifest (the canonical name is trial_generator_log.json).  Remove
    # that stale alias before rebuilding so manifest integrity has no hidden
    # UNTRACKED_FILE failure.
    stale_generator_log = bundle_dir / "generator_log.json"
    if stale_generator_log.exists():
        stale_generator_log.unlink()

    src_bundle = SOURCE_BUNDLES[season]
    v2_output = REF_DIR / info["folder"] / "DSSAT输出_v2"

    # --- Files copied from source bundle (FileX retention proof) ---
    # 25SP source bundle (XXQL2501) does not carry SOIL.SOL because the same
    # soil profile (IBTM910017) is shared across all three seasons. Use the
    # 25FA bundle's SOIL.SOL as the SOIL.SOL source for 25SP.
    SOIL_SOL_FALLBACK = EXPERIMENTS_DIR / "XXQL2502" / "SOIL.SOL"
    copied_from_v1: list[dict] = []
    files_to_copy_from_v1 = [
        f"{excode}.TMX",
        "SOIL.SOL",
        WEATHER_FILES[season],
        "DSSBatch.v48",
    ]
    for fname in files_to_copy_from_v1:
        src = src_bundle / fname
        if not src.exists() and fname == "SOIL.SOL" and SOIL_SOL_FALLBACK.exists():
            src = SOIL_SOL_FALLBACK
        if not src.exists():
            raise FileNotFoundError(f"Source bundle {src_bundle} missing: {fname}")
        dst = bundle_dir / fname
        copy_file(src, dst)
        rec = file_record(dst)
        rec["copied_from"] = str(src)
        if src != src_bundle / fname:
            rec["copied_from_note"] = "SOIL.SOL shared across seasons; sourced from XXQL2502 bundle"
        copied_from_v1.append(rec)

    # --- Files generated by trial observations adapter ---
    # Source file name -> destination file name (rename generator_log.json to avoid collision)
    trial_files: list[tuple[str, str]] = [
        (f"{excode}.TMA", f"{excode}.TMA"),
        (f"{excode}.TMT", f"{excode}.TMT"),
        ("observation_uncertainty.csv", "observation_uncertainty.csv"),
        ("fruit_quality_match_audit.csv", "fruit_quality_match_audit.csv"),
        ("generator_log.json", "trial_generator_log.json"),
    ]
    if season == "25SP":
        trial_files.append(("treatment_exclusion_audit.csv", "treatment_exclusion_audit.csv"))
    generated_trial: list[dict] = []
    for src_name, dst_name in trial_files:
        src = v2_output / src_name
        if not src.exists():
            raise FileNotFoundError(f"v2 output {v2_output} missing: {src_name}")
        dst = bundle_dir / dst_name
        copy_file(src, dst)
        rec = file_record(dst)
        rec["generated_by"] = "tools/experiments/build_trial_observations_v2_20260726.py"
        rec["generator_sha256"] = generators_sha["trial"]
        rec["source_v2_dir"] = str(src)
        generated_trial.append(rec)

    # --- Files generated by soil water adapter ---
    soil_files = [
        "soil_water_observations.csv",
        "soil_water_layer_mapping.csv",
        "soil_water_match_audit.csv",
        "soil_water_generator_log.json",
    ]
    generated_soil: list[dict] = []
    for fname in soil_files:
        src = v2_output / fname
        if not src.exists():
            raise FileNotFoundError(f"v2 output {v2_output} missing: {fname}")
        dst = bundle_dir / fname
        copy_file(src, dst)
        rec = file_record(dst)
        rec["generated_by"] = "tools/experiments/build_soil_water_observations.py"
        rec["generator_sha256"] = generators_sha["soil"]
        rec["source_v2_dir"] = str(src)
        generated_soil.append(rec)

    # --- Source workbook SHAs (from generator logs) ---
    trial_log_path = v2_output / "generator_log.json"
    soil_log_path = v2_output / "soil_water_generator_log.json"
    trial_log = json.loads(trial_log_path.read_text(encoding="utf-8")) if trial_log_path.exists() else {}
    soil_log = json.loads(soil_log_path.read_text(encoding="utf-8")) if soil_log_path.exists() else {}

    # Read v1 manifest for FileX retention proof
    v1_manifest_path = src_bundle / "input_manifest.json"
    v1_manifest = json.loads(v1_manifest_path.read_text(encoding="utf-8")) if v1_manifest_path.exists() else {}

    # --- Build input_manifest.json ---
    excl = TREATMENT_EXCLUSION[season]
    manifest = {
        "bundle_id": info["bundle_name"],
        "derived_from_bundle": src_bundle.name,
        "derived_from_manifest_sha256": sha256_file(v1_manifest_path) if v1_manifest_path.exists() else None,
        "spec_compliance": [
            "docs/三季FileA_FileT与不确定性适配计划_v1_20260726.md",
            "docs/土壤水分进入Phi与土壤参数预筛方案_v1_20260726.md",
        ],
        "created_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "season_id": season,
        "excode": excode,
        "intended_use": "actual_trial_parameter_calibration_v2",
        "scenario_type": "actual_trial_calibration",
        "scenario_role": "calibration",
        "observation_policy": "FileA_FileT_strict_fill_plus_SOIL_WATER_group",
        "treatment_plot_mapping": (
            "TN1-TN12 map one-to-one to plots 1-12" if season != "25SP"
            else "TN 2,3,4,5,9,10,11,12,13,14 map to plots 2-5,9-14; TN 1,6,7,8 excluded"
        ),
        "treatment_exclusion": {
            "excluded_tn": excl["excluded_tn"],
            "included_tn": excl["included_tn"],
            "reason": excl["reason"] or None,
            "audit_file": "treatment_exclusion_audit.csv" if season == "25SP" else None,
        },
        "initial_condition_policy": "observed_treatment_specific_no_counterfactual_pooling",
        "soil_analysis_policy": "observed_treatment_specific_no_counterfactual_pooling",
        "actual_trial_preservation": {
            "reference_filex": str(src_bundle / f"{excode}.TMX"),
            "reference_filex_sha256": sha256_file(src_bundle / f"{excode}.TMX"),
            "v1_bundle_manifest_id": v1_manifest.get("bundle_id"),
            "v1_bundle_manifest_sha256": sha256_file(v1_manifest_path) if v1_manifest_path.exists() else None,
            "filex_retention_proof": "TMX byte-for-byte copied from authoritative data/user/experiments/XXQL*; SOIL.SOL/WTH/DSSBatch.v48 sources and SHAs are recorded",
        },
        "filex_fix_status": {
            "25SP": "authoritative FileX copied from data/user/experiments/XXQL2501; 25SP treatment exclusion audited",
            "25FA": "authoritative FileX copied from data/user/experiments/XXQL2502; fertilizer management order audited",
            "26SP": "authoritative FileX copied from data/user/experiments/XXQL2601; fertilizer management order audited",
        }.get(season, "unknown"),
        "source_workbooks": {
            "trial_observations": trial_log.get("source_files", {}),
            "soil_water": soil_log.get("source_files", {}),
        },
        "generators": {
            "trial_observations": {
                "script": "tools/experiments/build_trial_observations_v2_20260726.py",
                "sha256": generators_sha["trial"],
            },
            "soil_water_observations": {
                "script": "tools/experiments/build_soil_water_observations.py",
                "sha256": generators_sha["soil"],
            },
        },
        "trial_observation_qa": trial_log.get("qa_metrics", {}),
        "soil_water_qa": soil_log.get("qa_metrics", {}),
        "soil_water_warnings": soil_log.get("warnings", []),
        # Formal input-manifest schema: files is always a flat list of
        # {name, sha256, bytes}.  Role-grouped provenance is retained under a
        # separate field and must never replace files.
        "files": copied_from_v1 + generated_trial + generated_soil,
        "files_by_role": {
            "copied_inputs": copied_from_v1,
            "generated_trial": generated_trial,
            "generated_soil": generated_soil,
        },
    }

    # Compute summary file count
    manifest["summary"] = {
        "total_files": len(manifest["files"]),
        "copied_from_v1_count": len(copied_from_v1),
        "generated_trial_count": len(generated_trial),
        "generated_soil_count": len(generated_soil),
    }

    manifest_path = bundle_dir / "input_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    print(f"  wrote {manifest_path}")

    return bundle_dir


def main() -> None:
    parser = argparse.ArgumentParser(description="Assemble v2 trial-calibration bundles.")
    parser.add_argument("--seasons", nargs="+", default=["25SP", "25FA", "26SP"],
                        choices=["25SP", "25FA", "26SP"])
    args = parser.parse_args()

    # Compute generator SHAs
    generators_sha = {
        "trial": sha256_file(Path(r"D:\Tomato_Cal\tools\experiments\build_trial_observations_v2_20260726.py")),
        "soil": sha256_file(Path(r"D:\Tomato_Cal\tools\experiments\build_soil_water_observations.py")),
    }
    print(f"Generator SHAs:")
    print(f"  trial: {generators_sha['trial']}")
    print(f"  soil:  {generators_sha['soil']}")

    for season in args.seasons:
        print(f"\n=== Assembling {season} bundle ===")
        bundle_dir = assemble_bundle(season, generators_sha)
        print(f"  bundle_dir: {bundle_dir}")
        files = sorted(p.name for p in bundle_dir.iterdir())
        print(f"  files ({len(files)}): {files}")


if __name__ == "__main__":
    main()
