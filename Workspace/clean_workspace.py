import os
import glob

def clean_workspace():
    """
    Cleans up intermediate files generated by DSSAT and PEST runs.
    Keeps:
    - Source code (*.py)
    - Base input templates (*.base, *.SOL, *.WTH)
    - PEST control definitions (*.pst, *.tpl, *.ins) generated by build_pest.py
    - Result directories (Calibration_Results, Sensitivity_Results)
    """
    workspace = os.getcwd()
    print(f"Cleaning workspace: {workspace}")

    # Patterns of files to delete
    patterns = [
        # DSSAT Outputs
        "*.OUT",
        "*.LST",
        
        # PEST Run Artifacts (Iterative results, logs, etc.)
        "tomato_cal.rec",
        "tomato_cal.log",
        "tomato_cal.rei",
        "tomato_cal.sen",
        "tomato_cal.seo",
        "tomato_cal.mtt",
        "tomato_cal.jco",
        "tomato_cal.rst",
        "tomato_cal.jac",
        "tomato_cal.par", # Final par if any
        "tomato_cal.*.par", # Iteration pars
        "tomato_cal.*.obs.csv", # Iteration obs
        "tomato_cal.*.pdc.csv",
        "tomato_cal.*.pcs.csv",
        "tomato_cal.*.rei",
        "tomato_cal.phi.*.csv",
        "tomato_cal.obs+noise.csv",
        "tomato_cal.weights.csv",
        
        # Sensitivity Analysis Artifacts (kept in root)
        "tomato_sen.rec",
        "tomato_sen.log",
        "tomato_sen.pst", # Re-generated by run_sensitivity.py
        "tomato_sen.msn", # Copy is in Results
        "tomato_sen.mio",
        "tomato_sen.mos",
        "tomato_sen.raw.csv",
        "tomato_sen.group.*",
        "tomato_sen.sen.par.csv",
        
        # Temp run info
        "run.info"
    ]

    deleted_count = 0
    for pat in patterns:
        files = glob.glob(pat)
        for f in files:
            try:
                os.remove(f)
                # print(f"Deleted: {f}") # Commented out to reduce noise
                deleted_count += 1
            except Exception as e:
                print(f"Error deleting {f}: {e}")
    
    print(f"Cleanup complete. Deleted {deleted_count} intermediate files.")
    print("Kept: Source codes, Base templates, Control files (.pst), and Result folders.")

if __name__ == "__main__":
    clean_workspace()
